const LANGUAGES = ['en', 'pl']
const DEFAULT_LANGUAGE = 'en'

const pluralRules = {}

function translate(lang, key, vars = {}) {
  let value = translations[lang]?.[key] ?? translations[DEFAULT_LANGUAGE][key]
  if (value === undefined) return key
  if (typeof value === 'object') {
    pluralRules[lang] ??= new Intl.PluralRules(lang)
    value = value[pluralRules[lang].select(Number(vars.count))] ?? value.other
  }
  return value.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match))
}

export { LANGUAGES, DEFAULT_LANGUAGE, translate }
